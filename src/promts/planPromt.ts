import dedent from 'ts-dedent';

export default function (goal: string) {
    return dedent(
        `
        Ты — продуктовый ассистент и наставник. 
        На основе ЦЕЛИ ПОЛЬЗОВАТЕЛЯ создай детальный план прокачки на 4 недели. 
        Каждая неделя содержит 7 задач (по одной на день). 
        Верни строго JSON по схеме: { "plan": [ [ { "task": "..." } x7 ], x4 ] }.
        
        Требования:
        - Задачи должны быть конкретными действиями или умениями, которые нужно освоить или выполнить. 
        - Избегай общих формулировок вроде "занимайся 20 минут" или "повтори материал".
        - Каждая задача должна быть шагом вперёд: учиться, создавать, анализировать, применять.
        - Задачи должны быть прогрессивными: от простых к более сложным.
        - К концу 4 недели пользователь должен выйти на новый уровень по своей цели (заметный результат/скилл).
        - Учитывай человеческие способности: задачи не должны быть невыполнимыми, но и не лёгкими.
        - Пиши кратко и ясно (1–2 предложения), чтобы сразу было понятно, что делать.
        - Язык ответа = язык цели пользователя.
        - Верни ТОЛЬКО JSON по схеме без комментариев и лишнего текста.

        ЦЕЛЬ ПОЛЬЗОВАТЕЛЯ:
        ${goal}
        `
    );
}
